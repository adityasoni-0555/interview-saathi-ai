import { useState, type FormEvent } from "react";
import { Loader2, Sparkles } from "lucide-react";
import { supabase } from "../lib/supabase";

type Mode = "signin" | "signup" | "forgot" | "recovery";

type Props = {
  recovery?: boolean;
  onRecoveryDone?: () => void;
};

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const MIN_PASSWORD = 8;

export default function AuthScreen({ recovery = false, onRecoveryDone }: Props) {
  const [mode, setMode] = useState<Mode>(recovery ? "recovery" : "signin");
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");

  function switchMode(next: Mode) {
    setMode(next);
    setError("");
    setNotice("");
  }

  function validate(): string | null {
    if (mode !== "recovery" && !EMAIL_RE.test(email.trim())) {
      return "Please enter a valid email address.";
    }
    if (mode === "signin" && !password) {
      return "Please enter your password.";
    }
    if ((mode === "signup" || mode === "recovery") && password.length < MIN_PASSWORD) {
      return `Password must be at least ${MIN_PASSWORD} characters.`;
    }
    return null;
  }

  async function handleSubmit(event: FormEvent) {
    event.preventDefault();
    setError("");
    setNotice("");

    const problem = validate();
    if (problem) {
      setError(problem);
      return;
    }

    setLoading(true);
    try {
      const cleanEmail = email.trim();
      if (mode === "signin") {
        const { error } = await supabase.auth.signInWithPassword({ email: cleanEmail, password });
        if (error) throw error;
      } else if (mode === "signup") {
        const { data, error } = await supabase.auth.signUp({ email: cleanEmail, password });
        if (error) throw error;
        if (!data.session) {
          setNotice("Account created! Check your email to confirm, then sign in.");
          setMode("signin");
          setPassword("");
        }
      } else if (mode === "forgot") {
        const { error } = await supabase.auth.resetPasswordForEmail(cleanEmail, {
          redirectTo: window.location.origin,
        });
        if (error) throw error;
        setNotice("If an account exists for that email, a reset link has been sent.");
      } else {
        const { error } = await supabase.auth.updateUser({ password });
        if (error) throw error;
        setPassword("");
        onRecoveryDone?.();
      }
    } catch (err) {
      setError(err instanceof Error ? err.message : "Something went wrong. Please try again.");
    } finally {
      setLoading(false);
    }
  }

  const titles: Record<Mode, [string, string, string]> = {
    signin: ["Welcome back", "Sign in to continue your interview prep.", "Sign in"],
    signup: ["Create your account", "Start practising with AI-powered mock interviews.", "Create account"],
    forgot: ["Reset your password", "We'll email you a secure reset link.", "Send reset link"],
    recovery: ["Choose a new password", "Enter a new password for your account.", "Update password"],
  };
  const [title, subtitle, cta] = titles[mode];

  return (
    <div className="auth-page">
      <div className="auth-hero">
        <div className="brand">
          <div className="brand-logo">S</div>
          <div>
            <div className="brand-name">INTERVIEW SAATHI</div>
            <div className="brand-sub">AI INTERVIEW COACH</div>
          </div>
        </div>
        <h1>Practise interviews. Get honest feedback. Walk in confident.</h1>
        <ul className="auth-points">
          <li><Sparkles size={16} /> Role-specific questions generated by AI</li>
          <li><Sparkles size={16} /> Instant scoring with strengths and gaps</li>
          <li><Sparkles size={16} /> Model answers and tips to improve</li>
        </ul>
      </div>

      <form className="auth-card panel" onSubmit={handleSubmit} noValidate>
        <h2>{title}</h2>
        <p className="muted">{subtitle}</p>

        {mode !== "recovery" && (
          <label className="field">
            <span>Email</span>
            <input
              type="email"
              autoComplete="email"
              value={email}
              onChange={(e) => setEmail(e.target.value)}
              placeholder="you@example.com"
              required
            />
          </label>
        )}

        {mode !== "forgot" && (
          <label className="field">
            <span>{mode === "recovery" ? "New password" : "Password"}</span>
            <input
              type="password"
              autoComplete={mode === "signin" ? "current-password" : "new-password"}
              value={password}
              onChange={(e) => setPassword(e.target.value)}
              placeholder={mode === "signin" ? "Your password" : `At least ${MIN_PASSWORD} characters`}
              minLength={mode === "signin" ? undefined : MIN_PASSWORD}
              required
            />
          </label>
        )}

        {error && <div className="alert alert-error" role="alert">{error}</div>}
        {notice && <div className="alert alert-info" role="status">{notice}</div>}

        <button className="primary-btn wide" type="submit" disabled={loading}>
          {loading && <Loader2 size={16} className="spin" />}
          {loading ? "Please wait..." : cta}
        </button>

        <div className="auth-links">
          {mode === "signin" && (
            <>
              <button type="button" className="link-btn" onClick={() => switchMode("forgot")}>
                Forgot password?
              </button>
              <button type="button" className="link-btn" onClick={() => switchMode("signup")}>
                New here? Create an account
              </button>
            </>
          )}
          {(mode === "signup" || mode === "forgot") && (
            <button type="button" className="link-btn" onClick={() => switchMode("signin")}>
              Back to sign in
            </button>
          )}
        </div>
      </form>
    </div>
  );
}
